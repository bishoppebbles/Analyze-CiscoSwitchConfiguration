<#
.SYNOPSIS
    Consolidates "Switch*" sheets from a source workbook into a summary sheet.
.DESCRIPTION
    This script reads all worksheets whose names start with "Switch" from a source Excel workbook (generated by Sam Pursglove's Analyze-CiscoSwitchConfiguration script) and builds a consolidated table of results at the start of the source workbook. 
.PARAMETER SourceWorkbookPath
    Path to the source Excel workbook (.xlsx). If omitted the script will prompt for the path.
.PARAMETER Hidden
    If present Excel will run hidden (no visible UI). Default is visible.
.EXAMPLE
    Consolidate-CiscoSwitchConfiguration.ps1 switch_analysis_output.xlsx 

    Generates a summary worksheet of the Cisco switch configuration analysis results produced by the Analyze-CiscoSwitchConfiguration.ps1 script.
.NOTES
    Version 1.01
    Olivia Tierney
#>

