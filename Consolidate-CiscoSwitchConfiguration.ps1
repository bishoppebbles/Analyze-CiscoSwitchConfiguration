    [Parameter(Position=0, HelpMessage = "Path to the source Excel workbook (.xlsx)")]
    [string]$SourceWorkbookPath,

    [Parameter(HelpMessage = "Run Excel hidden (no visible UI)")]
    [switch]$Hidden
)



